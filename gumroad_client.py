import os
import logging
import requests
from typing import Dict, List, Optional, Any

logger = logging.getLogger("GumroadPublisher")

class GumroadPublisher:
    """Official Gumroad API Publisher with mock mode & error resilience."""

    def __init__(self, access_token: Optional[str] = None):
        self.access_token = access_token or os.getenv("GUMROAD_ACCESS_TOKEN")
        host_parts = ["api", "gumroad", "com"]
        self.products_endpoint = f"https://{'.'.join(host_parts)}/v2/products"

    def publish_product(
        self,
        name: str,
        price_cents: int = 399,
        description: str = "Coloring page generated by 2026 Color World. Includes license key and printable line art.",
        tags: Optional[List[str]] = None,
        promo_code: str = "SUBSCRIBE50",
        discount_percent: int = 50
    ) -> Dict[str, Any]:

        if not self.access_token or self.access_token.strip() == "":
            logger.info("Running in Mock Mode (GUMROAD_ACCESS_TOKEN not configured)")
            mock_id = f"prod_mock_{abs(hash(name)) % 10000000}"
            return {
                "success": True,
                "mode": "mock",
                "product_id": mock_id,
                "product_url": f"https://gumroad.com/l/{mock_id}",
                "price": f"${price_cents / 100:.2f}",
                "is_licensed": True,
                "promo_code": promo_code,
                "discount": f"{discount_percent}% OFF",
                "message": "Mock listing successful. Set GUMROAD_ACCESS_TOKEN to enable real publishing."
            }

        try:
            payload = {
                "access_token": self.access_token,
                "name": name,
                "price_cents": price_cents,
                "description": description,
                "is_licensed": "true",
                "tags": ",".join(tags) if tags else ""
            }

            response = requests.post(self.products_endpoint, data=payload, timeout=10)
            res_data = response.json()

            if not res_data.get("success"):
                error_msg = res_data.get("message", "Unknown API error")
                logger.error(f"API Error: {error_msg}")
                return {"success": False, "error": error_msg}

            product = res_data.get("product", {})
            product_id = product.get("id")
            product_url = product.get("short_url")

            if product_id:
                promo_url = f"{self.products_endpoint}/{product_id}/offer_codes"
                promo_payload = {
                    "access_token": self.access_token,
                    "name": promo_code,
                    "percent_off": discount_percent
                }
                requests.post(promo_url, data=promo_payload, timeout=10)

            return {
                "success": True,
                "mode": "live",
                "product_id": product_id,
                "product_url": product_url,
                "price": f"${price_cents / 100:.2f}",
                "is_licensed": True,
                "promo_code": promo_code,
                "discount": f"{discount_percent}% OFF"
            }

        except Exception as e:
            logger.exception("Failed to connect to API")
            return {"success": False, "error": str(e)}
